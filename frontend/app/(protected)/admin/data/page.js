"use client";

import { useCallback, useEffect, useState } from "react";
import Link from "next/link";
import { getPurgePreview, purgeTransactions } from "@/lib/api";
import { useAuth } from "@/lib/auth-context";

// Bulk removal of dummy/demo data (stream simulator output, manual test
// scores). Hard delete — transactions, their decisions and alerts — see
// backend/transaction_admin.py. For picking individual rows, use the
// checkboxes on the dashboard feed or the alerts queue instead.

const SOURCES = [
  { key: "stream", label: "Stream simulator data", hint: "Transactions generated by the live stream (IDs starting with stream-)" },
  { key: "manual", label: "Manually scored data", hint: "Transactions scored through the form or POST /score (e.g. demo-…)" },
  { key: "all", label: "Everything", hint: "Every scored transaction, alert and decision" },
];

const AGES = [
  { key: "any", label: "Any age", ms: null },
  { key: "1h", label: "Older than 1 hour", ms: 60 * 60 * 1000 },
  { key: "1d", label: "Older than 1 day", ms: 24 * 60 * 60 * 1000 },
  { key: "7d", label: "Older than 7 days", ms: 7 * 24 * 60 * 60 * 1000 },
  { key: "30d", label: "Older than 30 days", ms: 30 * 24 * 60 * 60 * 1000 },
];

function cutoffFor(ageKey) {
  const ms = AGES.find((a) => a.key === ageKey)?.ms;
  return ms ? new Date(Date.now() - ms) : null;
}

export default function DataCleanupPage() {
  const { role } = useAuth();
  const [source, setSource] = useState("stream");
  const [age, setAge] = useState("any");
  const [count, setCount] = useState(null);
  const [loadingCount, setLoadingCount] = useState(false);
  const [deleting, setDeleting] = useState(false);
  const [result, setResult] = useState(null);
  const [error, setError] = useState("");

  const loadCount = useCallback(async () => {
    setLoadingCount(true);
    try {
      const { count: n } = await getPurgePreview(source, cutoffFor(age));
      setCount(n);
      setError("");
    } catch (err) {
      setError(err.message || "Failed to count matching transactions.");
    } finally {
      setLoadingCount(false);
    }
  }, [source, age]);

  useEffect(() => {
    if (role === "ADMIN") loadCount();
  }, [role, loadCount]);

  if (role !== "ADMIN") {
    return (
      <div className="min-h-screen flex items-center justify-center bg-slate-950 text-slate-400">
        <div className="text-center">
          <p className="text-lg font-medium text-slate-200 mb-2">Admins only</p>
          <p className="text-sm mb-4">You don&apos;t have permission to delete data.</p>
          <Link href="/dashboard" className="text-sm text-indigo-400 hover:text-indigo-300">
            ← Back to dashboard
          </Link>
        </div>
      </div>
    );
  }

  async function handlePurge() {
    const sourceLabel = SOURCES.find((s) => s.key === source).label.toLowerCase();
    const ageLabel = age === "any" ? "" : ` (${AGES.find((a) => a.key === age).label.toLowerCase()})`;
    if (!window.confirm(`Permanently delete ${count} transactions — ${sourceLabel}${ageLabel} — with their decisions and alerts? This cannot be undone.`)) {
      return;
    }
    setDeleting(true);
    setError("");
    setResult(null);
    try {
      setResult(await purgeTransactions(source, cutoffFor(age)));
      await loadCount();
    } catch (err) {
      setError(err.message || "Delete failed.");
    } finally {
      setDeleting(false);
    }
  }

  return (
    <div className="min-h-screen flex-1 bg-slate-950 text-slate-100">
      <header className="border-b border-slate-800 px-6 py-4 flex items-center justify-between flex-wrap gap-3">
        <div>
          <h1 className="text-lg font-semibold">Data Cleanup</h1>
          <p className="text-xs text-slate-500">Permanently delete dummy or demo transactions, with their decisions and alerts</p>
        </div>
        <Link href="/dashboard" className="text-sm text-slate-400 hover:text-white transition-colors">
          ← Dashboard
        </Link>
      </header>

      <main className="p-6 max-w-3xl mx-auto space-y-6">
        <div className="bg-slate-900 border border-slate-800 rounded-lg p-5 space-y-5">
          <div>
            <h2 className="text-sm font-medium text-slate-300 mb-3">What to delete</h2>
            <div className="space-y-2">
              {SOURCES.map((s) => (
                <label
                  key={s.key}
                  className={`flex items-start gap-3 rounded-md border px-3 py-2.5 cursor-pointer transition-colors ${
                    source === s.key ? "border-indigo-500 bg-indigo-500/10" : "border-slate-800 hover:border-slate-700"
                  }`}
                >
                  <input
                    type="radio"
                    name="source"
                    value={s.key}
                    checked={source === s.key}
                    onChange={() => setSource(s.key)}
                    className="mt-1 accent-indigo-500"
                  />
                  <span>
                    <span className="block text-sm text-slate-200">{s.label}</span>
                    <span className="block text-xs text-slate-500">{s.hint}</span>
                  </span>
                </label>
              ))}
            </div>
          </div>

          <div>
            <label className="block text-sm font-medium text-slate-300 mb-2">Age</label>
            <select
              value={age}
              onChange={(e) => setAge(e.target.value)}
              className="rounded-md bg-slate-800 border border-slate-700 px-3 py-2 text-sm text-white focus:outline-none focus:ring-2 focus:ring-indigo-500"
            >
              {AGES.map((a) => (
                <option key={a.key} value={a.key}>
                  {a.label}
                </option>
              ))}
            </select>
          </div>

          <div className="flex items-center justify-between flex-wrap gap-3 pt-4 border-t border-slate-800">
            <p className="text-sm text-slate-400">
              {loadingCount ? "Counting…" : count === null ? "—" : (
                <>
                  <span className="text-lg font-semibold text-white">{count.toLocaleString()}</span> matching transaction{count === 1 ? "" : "s"}
                </>
              )}
            </p>
            <button
              onClick={handlePurge}
              disabled={deleting || loadingCount || !count}
              className="rounded-md bg-rose-600 hover:bg-rose-500 disabled:opacity-50 disabled:hover:bg-rose-600 text-white text-sm font-medium px-5 py-2 transition-colors"
            >
              {deleting ? "Deleting…" : "Delete permanently"}
            </button>
          </div>
        </div>

        {error && <p className="text-sm text-rose-400">{error}</p>}
        {result && (
          <div className="bg-emerald-500/10 border border-emerald-500/30 rounded-lg px-4 py-3 text-sm text-emerald-300">
            Deleted {result.deleted_transactions.toLocaleString()} transactions, {result.deleted_decisions.toLocaleString()} decisions
            and {result.deleted_alerts.toLocaleString()} alerts.
          </div>
        )}

        <p className="text-xs text-slate-500">
          To delete specific transactions instead, tick their checkboxes on the dashboard&apos;s live feed or in the alerts
          queue and use <span className="text-slate-300">Delete selected</span>.
        </p>
      </main>
    </div>
  );
}
